export function getQuestionsBySubject(subject: Subject): Question[] {
  return sampleQuestions.filter((q) => q.subject === subject);
}

export function getQuestionsByTopic(subject: Subject, topic: string): Question[] {
  return sampleQuestions.filter((q) => q.subject === subject && q.topic === topic);
}

export function getQuestionById(id: string): Question | undefined {
  return sampleQuestions.find((q) => q.id === id);
}

export function getRelatedQuestions(questionId: string, excludeId?: string): Question[] {
  const question = getQuestionById(questionId);
  if (!question) return [];
  const relatedIds = question.relatedQuestionIds ?? [];
  const related = relatedIds
    .map((id) => getQuestionById(id))
    .filter((q): q is Question => q !== undefined && q.id !== excludeId);
  if (related.length > 0) return related;
  return sampleQuestions
    .filter((q) => q.subject === question.subject && q.topic === question.topic && q.id !== questionId)
    .slice(0, 3);
}
